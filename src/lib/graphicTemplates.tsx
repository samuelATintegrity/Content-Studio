// Promo headline auto-shrinks based on character length. Catchphrases
// are unpredictable in length — a 6-word hook fits beautifully at 124px,
// a 14-word one needs to drop to ~88px to avoid overflowing the card.
function promoHeadlineFontSize(text: string): number {
  const len = text.length;
  if (len <= 28) return 124;
  if (len <= 44) return 108;
  if (len <= 64) return 92;
  return 76;
}

function promoSublineFontSize(text: string): number {
  const len = text.length;
  if (len <= 60) return 56;
  if (len <= 100) return 46;
  return 38;
}

